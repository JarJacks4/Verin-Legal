function buildIntegrationReportPdf({ matter, receipts, clio, generatedAt, generatedBy }) {
  const PDFDocument = require('pdfkit');
  const { NAVY, TEAL, INK, MUTED, RULE } = COLORS;
  const doc = new PDFDocument({ size: 'LETTER', layout: 'landscape', margins: { top: 48, bottom: 56, left: 48, right: 48 }, bufferPages: true });
  doc.registerFont('Sans', FONTS.sans);
  doc.registerFont('Bold', FONTS.bold);
  doc.registerFont('Mono', FONTS.mono);
  doc.registerFont('Serif', FONTS.serif);
  const chunks = [];
  doc.on('data', (c) => chunks.push(c));
  const done = new Promise((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });
  const left = doc.page.margins.left;
  const width = doc.page.width - left - doc.page.margins.right;
  const bottom = () => doc.page.height - doc.page.margins.bottom;

  doc.rect(left, doc.y, width, 64).fill(NAVY);
  const top = doc.y;
  doc.font('Bold').fontSize(8).fillColor('#E4EEEF').text('VERIN EVIDENCE RECORD', left + 18, top + 14, { characterSpacing: 1.6 });
  doc.font('Serif').fontSize(18).fillColor('#FBFAF8').text('Integration Report', left + 18, top + 28);
  doc.font('Sans').fontSize(9).fillColor('#E4EEEF').text(`Generated ${human(generatedAt)}\nby ${printable(generatedBy)}`, left, top + 18, { width: width - 18, align: 'right' });
  doc.y = top + 80;

  const kv = [
    ['Matter', matter.title],
    ['Client', matter.clientName],
    ['Cause number', matter.caseNumber],
    ['Evidence items', `${receipts.length} total · ${receipts.filter((r) => r.state === 'Processed').length} processed`],
    ['Chain head', matter.chainHeadHash],
  ];
  for (const [k, v] of kv) {
    const y = doc.y;
    doc.font('Sans').fontSize(9).fillColor(MUTED).text(k, left, y, { width: 120 });
    doc.font(k === 'Chain head' ? 'Mono' : 'Sans').fontSize(k === 'Chain head' ? 8 : 10).fillColor(INK).text(printable(dash(v)), left + 120, y, { width: width - 120 });
    doc.moveDown(0.3);
  }
  doc.moveDown(0.6);

  const section = (name, synced, sub, rows, emptyNote) => {
    if (doc.y + 60 > bottom()) doc.addPage();
    doc.moveTo(left, doc.y).lineTo(left + width, doc.y).lineWidth(0.5).strokeColor(RULE).stroke();
    doc.moveDown(0.5);
    doc.font('Bold').fontSize(11).fillColor(INK).text(name, left, doc.y, { continued: true });
    doc.font('Sans').fontSize(9).fillColor(synced ? TEAL : MUTED).text(`   ${synced ? 'Synced' : 'Not synced'} · ${sub}`);
    doc.moveDown(0.4);
    if (!synced || !rows.length) {
      doc.font('Sans').fontSize(9).fillColor(MUTED).text(emptyNote, left, doc.y, { width });
      doc.moveDown(0.8);
      return;
    }
    const cols = [
      ['Content', 0.34],
      ['Kind', 0.1],
      ['Received', 0.14],
      ['SHA-256 at receipt', 0.21],
      ['Chain entry', 0.21],
    ];
    const header = () => {
      let x = left;
      const y = doc.y;
      for (const [c, w] of cols) {
        doc.font('Bold').fontSize(7.5).fillColor(MUTED).text(c.toUpperCase(), x, y, { width: width * w - 6 });
        x += width * w;
      }
      doc.moveDown(0.5);
    };
    header();
    for (const r of rows) {
      const cells = [r.headline, r.itemKind, human(r.receivedAt), r.itemHash, r.entryHash];
      const heights = cells.map((v, i) => {
        doc.font(i >= 3 ? 'Mono' : 'Sans').fontSize(i >= 3 ? 7 : 8.5);
        return doc.heightOfString(printable(dash(v)), { width: width * cols[i][1] - 6 });
      });
      const h = Math.max(...heights) + 6;
      if (doc.y + h > bottom()) {
        doc.addPage();
        header();
      }
      const y = doc.y;
      let x = left;
      cells.forEach((v, i) => {
        doc.font(i >= 3 ? 'Mono' : 'Sans').fontSize(i >= 3 ? 7 : 8.5).fillColor(INK).text(printable(dash(v)), x, y, { width: width * cols[i][1] - 6 });
        x += width * cols[i][1];
      });
      doc.y = y + h;
    }
    doc.moveDown(0.8);
  };

  const processed = receipts.filter((r) => r.state === 'Processed');
  section(
    'Clio Manage',
    clio.synced,
    clio.matchedTo ? `matched to ${clio.matchedTo}` : 'not matched',
    processed,
    clio.matchedTo ? 'Matched — push the record from the Practice tab to sync it.' : 'Not connected.',
  );
  section('MyCase', false, 'coming soon', [], 'Coming soon — needs partner approval from MyCase.');
  section('Smokeball', false, 'coming soon', [], 'Coming soon.');

  doc.moveDown(0.5);
  doc.font('Sans').fontSize(8).fillColor(MUTED).text(
    'Each push uploads a newly generated record; earlier uploads stay in the practice system. A failed push is treated as a trust incident and surfaced in Verin. Verin offers no opinion on authenticity, completeness or admissibility.',
    left,
    doc.y,
    { width },
  );

  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    doc.font('Sans').fontSize(7.5).fillColor(MUTED).text(`Verin integration report · ${printable(matter.title)} · page ${i + 1} of ${range.count}`, left, doc.page.height - 36, { width, align: 'center' });
  }
  doc.end();
  return done;
}

exports.exportIntegrationReport = onCall({ timeoutSeconds: 120, memory: '1GiB' }, async (request) => {
  const uid = requireAuth(request);
  const db = getFirestore();
  const bucket = getStorage().bucket();
  const { ref, snap } = await loadMatterForUser(db, uid, (request.data || {}).matterId, P.DEFAULT_FIRM_ID.value());
  const md = snap.data() || {};
  const { receipts } = await loadMatterData(db, ref);
  const generatedAt = new Date();
  const generatedBy = await generatedByName(db, uid, request);
  const title = md.matterName || md.caseTitle || ref.id;
  const rows = receipts
    .filter(({ data: r }) => r.isDuplicate !== true)
    .map(({ data: r }) => ({
      headline: headlineOf(r),
      itemKind: r.itemKind || '',
      receivedAt: toDate(r.receivedAt),
      itemHash: r.item_hash || '',
      entryHash: r.entryHash || '',
      state: r.classificationLabel || 'Processed',
    }))
    .sort((a, b) => (a.receivedAt ? a.receivedAt.getTime() : 0) - (b.receivedAt ? b.receivedAt.getTime() : 0));
  const clioRef = md.clioMatterID || md.providerMatterReference || '';
  const pdf = await buildIntegrationReportPdf({
    matter: { title, clientName: md.clientName || '', caseNumber: md.caseNumber || '', chainHeadHash: md.chainHeadHash || '' },
    receipts: rows,
    clio: { synced: !!md.clioSyncedAt && !!clioRef, matchedTo: md.clioMatterDisplayNumber || clioRef },
    generatedAt,
    generatedBy,
  });
  const sha256 = crypto.createHash('sha256').update(pdf).digest('hex');
  const stamp = generatedAt.toISOString().replace(/[-:]/g, '').replace(/\.\d+Z$/, 'Z');
  const fileName = `${slug(title)}-integration-report-${stamp}.pdf`;
  const storagePath = `matters/${ref.id}/exports/${fileName}`;
  const token = crypto.randomUUID();
  await bucket.file(storagePath).save(pdf, {
    resumable: false,
    contentType: 'application/pdf',
    metadata: { contentDisposition: `inline; filename="${fileName}"`, metadata: { firebaseStorageDownloadTokens: token, sha256, generatedBy: uid } },
  });
  return {
    downloadUrl: `https://firebasestorage.googleapis.com/v0/b/${bucket.name}/o/${encodeURIComponent(storagePath)}?alt=media&token=${token}`,
    fileName,
    sha256,
  };
});

