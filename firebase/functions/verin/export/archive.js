// Verin Legal — record archives and reports.
//
//   exportRecordZip          One matter, standalone-verifiable: manifest.json,
//                            exhibits/ (files exactly as received),
//                            timestamps/*.tsr (RFC 3161 tokens),
//                            certificate.pdf, verify.py, README.txt.
//   exportFirmData           Every matter's manifest in one ZIP (no exhibits).
//   exportIntegrationReport  PDF: what was synced to each practice system,
//                            item by item, with hashes.

