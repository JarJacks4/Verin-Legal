const toDate = (v) => (v && typeof v.toDate === 'function' ? v.toDate() : v instanceof Date ? v : null);
const isoOrNull = (v) => {
  const d = toDate(v);
  return d ? d.toISOString() : null;
};

function slug(s) {
  return (
    String(s || 'matter')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 60) || 'matter'
  );
}

function safeName(s) {
  return String(s || 'file').replace(/[\\/:*?"<>|\u0000-\u001f]/g, '_').slice(0, 120);
}

function headlineOf(r) {
  if (r.content) return r.content;
  const kind = r.itemKind ? r.itemKind.replace(/_/g, ' ') : 'Item';
  return r.channel ? `${kind} via ${r.channel}` : kind;
}

/// Pure: builds the manifest object from plain matter / receipt / chain data.
/// receipts: [{ id, data }]; chain: [entry data]. exhibitFor(receipt) -> path or null.
function buildManifest({ matterId, matter, receipts, chain, exportedAt, exportedBy, exhibitFor, tsrFor }) {
  const sortedChain = [...chain].sort((a, b) => (a.seq || 0) - (b.seq || 0));
  const verification = verifyEntries(sortedChain);
  return {
    format: 'verin-record-manifest',
    format_version: 1,
    exported_at: exportedAt.toISOString(),
    exported_by: exportedBy,
    hash_algorithm: 'SHA-256',
    chain_formula: 'entry_hash = SHA256(prev_hash + "|" + item_hash + "|" + received_at + "|" + origin_digest); first prev_hash = 64 zeros',
    matter: {
      id: matterId,
      name: matter.matterName || matter.caseTitle || '',
      client: matter.clientName || '',
      cause_number: matter.caseNumber || '',
      practice_area: matter.practiceArea || matter.matterType || '',
      status: matter.status || '',
      opened_at: isoOrNull(matter.openedAt),
      archive_build: matter.isArchiveBuild === true,
    },
    chain_head: matter.chainHeadHash || verification.head || null,
    chain_verification_at_export: {
      ok: verification.ok,
      verified_entries: verification.verified,
      legacy_entries: verification.legacy,
      broken_at: verification.brokenAt || null,
      reason: verification.reason || null,
    },
    receipts: receipts
      .map(({ id, data: r }) => ({
        id,
        received_at: isoOrNull(r.receivedAt),
        channel: r.channel || '',
        from: r.fromLabel || '',
        item_kind: r.itemKind || '',
        content: headlineOf(r),
        original_file_name: r.originalFileName || '',
        content_type: r.contentType || '',
        size_bytes: r.sizeBytes || null,
        item_hash: r.item_hash || '',
        chain_seq: r.chainSeq || null,
        entry_hash: r.entryHash || '',
        state: r.classificationLabel || '',
        is_duplicate: r.isDuplicate === true,
        origin_fidelity: r.originFidelity || null,
        duration_seconds: r.durationSeconds || null,
        evidence_date: isoOrNull(r.resolvedDate),
        evidence_date_confidence: r.dateConfidence || null,
        evidence_date_source: r.dateSource || null,
        rfc3161: r.tsaGenTime ? { tsa: r.tsaName || '', gen_time: isoOrNull(r.tsaGenTime), token_file: tsrFor ? tsrFor({ id, data: r }) : null } : null,
        exhibit_file: exhibitFor ? exhibitFor({ id, data: r }) : null,
        description: r.description || '',
        chain_of_custody_notes: r.custodyNotes || '',
        ai_reading: r.aiSummary ? { summary: r.aiSummary, note: 'Reading aid generated by AI; cites the exhibit and never replaces it.' } : null,
      }))
      .sort((a, b) => String(a.received_at).localeCompare(String(b.received_at))),
    chain: sortedChain.map((e) => ({
      seq: e.seq || 0,
      prev_hash: e.prevHash || null,
      item_hash: e.itemHash || null,
      received_at: e.receivedAtIso || null,
      origin_digest: e.originDigest || null,
      entry_hash: e.entryHash || null,
    })),
  };
}

function readmeText(manifest) {
  return [
    'VERIN EVIDENCE RECORD',
    '',
    `Matter:       ${manifest.matter.name}`,
    `Exported:     ${manifest.exported_at}`,
    `Chain head:   ${manifest.chain_head || '-'}`,
    '',
    'Contents',
    '  manifest.json     every receipt with its SHA-256 at receipt, and the hash chain',
    '  exhibits/         the files exactly as received (named <chain #>-<original name>)',
    '  timestamps/       RFC 3161 timestamp tokens over each item hash (.tsr)',
    '  certificate.pdf   Certificate of Preparation with the itemized exhibit index',
    '  verify.py         standalone verifier (Python 3, standard library only)',
    '',
    'To verify',
    '  1. Unzip this archive.',
    '  2. Run:  python3 verify.py',
    '  3. PASS means every exhibit hashes to the value recorded at receipt and the',
    '     hash chain recomputes to the chain head above. A failure names the first',
    '     broken link.',
    '',
    'Timestamps can be inspected with OpenSSL:  openssl ts -reply -in timestamps/<file>.tsr -text',
    '',
    'The record shows what arrived and when. It does not describe what happened to',
    'a file before it arrived. Verin offers no opinion on authenticity, completeness',
    'or admissibility; those determinations belong to counsel and the Court.',
    '',
  ].join('\n');
}

function makeZip() {
  const archiver = require('archiver');
  const zip = archiver('zip', { zlib: { level: 6 } });
  const out = new PassThrough();
  zip.pipe(out);
  return { zip, out };
}

// Adds one streamed entry and waits until archiver has written it, so only
// one exhibit is being downloaded at a time (exhibits can be up to 2 GB).
function appendAndWait(zip, openStream, name) {
  return new Promise((resolve, reject) => {
    const onEntry = (entry) => {
      if (entry.name === name) {
        zip.removeListener('entry', onEntry);
        zip.removeListener('error', onError);
        resolve();
      }
    };
    const onError = (e) => {
      zip.removeListener('entry', onEntry);
      reject(e);
    };
    zip.on('entry', onEntry);
    zip.once('error', onError);
    const stream = openStream();
    stream.on('error', onError);
    zip.append(stream, { name });
  });
}

async function saveStream(bucket, storagePath, out, contentType, fileName, uid) {
  const token = crypto.randomUUID();
  const hash = crypto.createHash('sha256');
  let bytes = 0;
  out.on('data', (c) => {
    hash.update(c);
    bytes += c.length;
  });
  await new Promise((resolve, reject) => {
    out
      .pipe(
        bucket.file(storagePath).createWriteStream({
          resumable: false,
          contentType,
          metadata: { contentDisposition: `attachment; filename="${fileName}"`, metadata: { firebaseStorageDownloadTokens: token, generatedBy: uid } },
        }),
      )
      .on('finish', resolve)
      .on('error', reject);
  });
  return {
    sha256: hash.digest('hex'),
    bytes,
    downloadUrl: `https://firebasestorage.googleapis.com/v0/b/${bucket.name}/o/${encodeURIComponent(storagePath)}?alt=media&token=${token}`,
  };
}

async function loadMatterData(db, ref) {
  const [receiptSnap, chainSnap] = await Promise.all([
    db.collection('Receipts').where('matterId', '==', ref).get(),
    db.collection('chainEntries').where('matterID', '==', ref).get(),
  ]);
  return {
    receipts: receiptSnap.docs.map((d) => ({ id: d.id, data: d.data() })),
    chain: chainSnap.docs.map((d) => d.data()),
  };
}

async function generatedByName(db, uid, request) {
  const user = await db.collection('users').doc(uid).get();
  return (user.exists && (user.get('display_name') || user.get('email'))) || (request.auth.token && request.auth.token.email) || uid;
}

function pdfReceipts(receipts) {
  return receipts
    .map(({ id, data: r }) => ({
      id,
      receivedAt: toDate(r.receivedAt),
      channel: r.channel || '',
      itemKind: r.itemKind || '',
      headline: headlineOf(r),
      itemHash: r.item_hash || '',
      entryHash: r.entryHash || '',
      chainSeq: r.chainSeq || 0,
      detectedPlatform: r.detectedPlatform || '',
      threadMessages: Array.isArray(r.threadMessages) ? r.threadMessages : [],
    }))
    .sort((a, b) => (a.receivedAt ? a.receivedAt.getTime() : 0) - (b.receivedAt ? b.receivedAt.getTime() : 0));
}

exports.exportRecordZip = onCall({ timeoutSeconds: 540, memory: '2GiB' }, async (request) => {
  const uid = requireAuth(request);
  const db = getFirestore();
  const bucket = getStorage().bucket();
  const { ref, snap } = await loadMatterForUser(db, uid, (request.data || {}).matterId, P.DEFAULT_FIRM_ID.value());
  const md = snap.data() || {};
  const { receipts, chain } = await loadMatterData(db, ref);
  const exportedAt = new Date();
  const exportedBy = await generatedByName(db, uid, request);
  const title = md.matterName || md.caseTitle || ref.id;

  const exhibitName = ({ id, data: r }) => {
    if (!r.sourceStoragePath) return null;
    const seq = String(r.chainSeq || 0).padStart(3, '0');
    return `exhibits/${seq}-${safeName(r.originalFileName || `${id}${path.extname(r.sourceStoragePath)}`)}`;
  };
  const tsrName = ({ id, data: r }) => (r.tsaTokenPath ? `timestamps/${String(r.chainSeq || 0).padStart(3, '0')}-${id}.tsr` : null);
  const manifest = buildManifest({ matterId: ref.id, matter: md, receipts, chain, exportedAt, exportedBy, exhibitFor: exhibitName, tsrFor: tsrName });

  let certificate = null;
  try {
    const verification = verifyEntries([...chain].sort((a, b) => (a.seq || 0) - (b.seq || 0)));
    certificate = await buildRecordPdf({
      matter: {
        id: ref.id,
        title,
        clientName: md.clientName || '',
        caseNumber: md.caseNumber || '',
        assignedCounsel: md.assignedCounsel || '',
        practiceArea: md.practiceArea || '',
        openedAt: toDate(md.openedAt),
        redactionCount: md.redactionCount || 0,
        redactionCategories: md.redactionCategories || '',
        hashChainLastAnchoredAt: toDate(md.hashChainLastAnchoredAt),
        chainHeadHash: md.chainHeadHash || '',
      },
      receipts: pdfReceipts(receipts),
      chain: [...chain]
        .sort((a, b) => (a.seq || 0) - (b.seq || 0))
        .map((e) => ({ seq: e.seq, prevHash: e.prevHash || '', itemHash: e.itemHash || '', receivedAtIso: e.receivedAtIso || '', originDigest: e.originDigest || '', entryHash: e.entryHash || '' })),
      verification,
      generatedAt: exportedAt,
      generatedBy: exportedBy,
    });
  } catch (e) {
    console.error('exportRecordZip: certificate failed', e);
  }

  const stamp = exportedAt.toISOString().replace(/[-:]/g, '').replace(/\.\d+Z$/, 'Z');
  const fileName = `${slug(title)}-record-${stamp}.zip`;
  const storagePath = `matters/${ref.id}/exports/${fileName}`;
  const { zip, out } = makeZip();
  const saved = saveStream(bucket, storagePath, out, 'application/zip', fileName, uid);

  zip.append(JSON.stringify(manifest, null, 2), { name: 'manifest.json' });
  zip.append(readmeText(manifest), { name: 'README.txt' });
  zip.append(fs.readFileSync(path.join(__dirname, 'verify.py')), { name: 'verify.py', mode: 0o755 });
  if (certificate) zip.append(certificate, { name: 'certificate.pdf' });
  let exhibits = 0;
  for (const r of receipts) {
    const name = exhibitName(r);
    if (name) {
      const f = bucket.file(r.data.sourceStoragePath);
      const [exists] = await f.exists();
      if (exists) {
        await appendAndWait(zip, () => f.createReadStream(), name);
        exhibits++;
      }
    }
    const t = tsrName(r);
    if (t) {
      const tf = bucket.file(r.data.tsaTokenPath);
      const [texists] = await tf.exists();
      if (texists) await appendAndWait(zip, () => tf.createReadStream(), t);
    }
  }
  await zip.finalize();
  const result = await saved;

  await ref.collection('exports').add({
    kind: 'record_zip',
    storagePath,
    fileName,
    sha256: result.sha256,
    bytes: result.bytes,
    items: receipts.length,
    exhibits,
    chainHead: manifest.chain_head,
    chainOk: manifest.chain_verification_at_export.ok,
    generatedByUid: uid,
    generatedAt: FieldValue.serverTimestamp(),
  });

  return { downloadUrl: result.downloadUrl, fileName, sha256: result.sha256, items: receipts.length, exhibits, storagePath };
});

exports.exportFirmData = onCall({ timeoutSeconds: 540, memory: '1GiB' }, async (request) => {
  const uid = requireAuth(request);
  const db = getFirestore();
  const bucket = getStorage().bucket();
  const firmId = await firmIdForUser(db, uid, P.DEFAULT_FIRM_ID.value());
  const mattersSnap = await db.collection('Matters').where('firmID', '==', firmId).get();
  const exportedAt = new Date();
  const exportedBy = await generatedByName(db, uid, request);

  const stamp = exportedAt.toISOString().replace(/[-:]/g, '').replace(/\.\d+Z$/, 'Z');
  const fileName = `verin-export-${slug(firmId)}-${stamp}.zip`;
  const storagePath = `exports/${slug(firmId)}/${fileName}`;
  const { zip, out } = makeZip();
  const saved = saveStream(bucket, storagePath, out, 'application/zip', fileName, uid);

  const index = [];
  for (const m of mattersSnap.docs) {
    const { receipts, chain } = await loadMatterData(db, m.ref);
    const manifest = buildManifest({ matterId: m.id, matter: m.data(), receipts, chain, exportedAt, exportedBy });
    const folder = `${slug(manifest.matter.name || m.id)}-${m.id.slice(0, 6)}`;
    zip.append(JSON.stringify(manifest, null, 2), { name: `${folder}/manifest.json` });
    index.push({ id: m.id, name: manifest.matter.name, receipts: manifest.receipts.length, chain_head: manifest.chain_head, folder });
  }
  zip.append(JSON.stringify({ exported_at: exportedAt.toISOString(), exported_by: exportedBy, firm: firmId, matters: index }, null, 2), { name: 'index.json' });
  zip.append(
    'Verin firm data export: one folder per matter with its manifest (receipts, hashes, hash chain).\nExhibit files are not included; export a single matter\'s record ZIP for those.\n',
    { name: 'README.txt' },
  );
  await zip.finalize();
  const result = await saved;
  return { downloadUrl: result.downloadUrl, fileName, matters: index.length, sha256: result.sha256 };
});

